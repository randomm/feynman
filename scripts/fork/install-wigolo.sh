#!/bin/sh
# Fork-owned. Installs the pinned wigolo runtime that feynman_web_* uses by default.
# Run from the repo root under the .nvmrc Node:  sh scripts/fork/install-wigolo.sh
#
# What it does:
#   1. Installs wigolo@$WIGOLO_PIN into a dedicated prefix (not the npx cache).
#   2. Pre-downloads wigolo's local models with `warmup` (large one-time download).
#   3. Writes ~/.feynman/bin/wigolo, a wrapper that pins the Node binary used here
#      (better-sqlite3 is a native module and must match that Node) and points
#      wigolo's OpenAI-compatible LLM at the Trail Openers endpoint for `research`.
#
# The API key is NOT handled here: wigolo already stores it in its own keychain
# entry (`wigolo doctor` shows "openai configured (keychain)").
set -eu

cd "$(dirname "$0")/../.."

WIGOLO_PIN="0.2.1"
PREFIX="${FEYNMAN_WIGOLO_PREFIX:-$HOME/.feynman/tools/wigolo}"
BIN_DIR="$HOME/.feynman/bin"
WRAPPER="$BIN_DIR/wigolo"
LLM_BASE_URL="${FEYNMAN_WIGOLO_LLM_BASE_URL:-https://llm.trailopeners.com/v1}"
LLM_MODEL="${FEYNMAN_WIGOLO_LLM_MODEL:-RedHatAI/Qwen3.8-27B-INT4}"

want=$(tr -d '[:space:]' < .nvmrc)
have=$(node -p "process.versions.node")
if [ "$want" != "$have" ]; then
	echo "warn  node is $have but .nvmrc wants $want; the native module is built for $have" >&2
fi

mkdir -p "$PREFIX" "$BIN_DIR"
npm install --prefix "$PREFIX" --no-audit --no-fund "wigolo@$WIGOLO_PIN"

NODE_ABS=$(node -p "process.execPath")
ENTRY="$PREFIX/node_modules/wigolo/dist/index.js"
if [ ! -f "$ENTRY" ]; then
	echo "fail  wigolo entry point not found at $ENTRY" >&2
	exit 1
fi

"$NODE_ABS" "$ENTRY" warmup

cat > "$WRAPPER" <<EOF
#!/bin/sh
# Generated by scripts/fork/install-wigolo.sh (wigolo@$WIGOLO_PIN). Re-run the script to change it.
export WIGOLO_LLM_PROVIDER=openai
export OPENAI_BASE_URL="\${OPENAI_BASE_URL:-$LLM_BASE_URL}"
export WIGOLO_LLM_MODEL="\${WIGOLO_LLM_MODEL:-$LLM_MODEL}"
exec "$NODE_ABS" "$ENTRY" "\$@"
EOF
chmod +x "$WRAPPER"

echo "ok    wigolo@$WIGOLO_PIN installed under $PREFIX"
echo "ok    wrapper written to $WRAPPER (node: $NODE_ABS)"
echo "      feynman_web_* finds it automatically; override with FEYNMAN_WIGOLO_BIN if needed"
